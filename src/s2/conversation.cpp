void PauseConversationCategories(bool paused) {
    for (auto &buffer : conversationData.buffers) {
        if (!buffer.callback || !buffer.pauseEnabled)
            continue;

        if (paused) {
            if (!buffer.stream.handle || !buffer.stream.paused) {
                PauseConversation(&buffer, true);
                buffer.pauseOwned = 1;
            }
        } else if (buffer.pauseOwned) {
            if (buffer.stream.handle && buffer.stream.paused)
                PauseConversation(&buffer, false);
            buffer.pauseOwned = 0;
        }
    }
}
