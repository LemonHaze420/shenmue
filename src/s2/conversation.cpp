ConversationBuffer *shenPlayAudio(const char *voiceCode, shen_name speaker, std::uint32_t playFlags, bool showSubtitles, std::int32_t *sceneRemap) {
    std::array<char, 12> code{};
    std::strncpy(code.data(), voiceCode, code.size());
    std::uint32_t restoreCode = 0;
    if (GetConversationAudioLanguage() == 1) {
        for (const std::array<std::uint32_t, 7> &remap : CONVERSATION_JAPANESE_CODE_REMAPS) {
            const std::array<std::uint32_t, 3> key = std::bit_cast<std::array<std::uint32_t, 3>>(code);
            if (key[0] == remap[0] && key[1] == remap[1] && key[2] == remap[2]) {
                std::memcpy(code.data(), remap.data() + 3, code.size());
                restoreCode = remap[6];
            }
        }
    }
    for (char &value : code)
        if (value >= 'a' && value <= 'z')
            value -= 'a' - 'A';
    const std::array<std::uint32_t, 3> key = std::bit_cast<std::array<std::uint32_t, 3>>(code);
    const std::uint32_t *record = nullptr;
    ConversationResource *resource = resources;
    for (std::uint32_t remaining = 16; remaining; --remaining, ++resource) {
        if (!resource->bankName[0])
            continue;
        const std::uint32_t *index = reinterpret_cast<const std::uint32_t *>(resource->index);
        switch (index[0]) {
        case SHEN_NAME(IDXA): {
            const std::uint32_t *table = FindConversationIndexChunk(index, SHEN_NAME(TABL));
            if (!table)
                break;
            const std::uint32_t *groups = FindConversationIndexChunk(index, SHEN_NAME(SIDX));
            if (!groups)
                break;
            for (const std::uint32_t *group = groups + 2; group[0] != SHEN_NAME(ENDI) && !record; group += 2) {
                if (group[0] != key[0])
                    continue;
                const std::int32_t begin = std::bit_cast<std::int32_t>(group[1]);
                for (const std::uint32_t *entry = table + 2 + 5LL * begin; entry[0] == key[0]; entry += 5) {
                    if (entry[1] == key[1] && entry[2] == key[2]) {
                        record = entry;
                        break;
                    }
                }
            }
            break;
        }
        case SHEN_NAME(IDXB):
            record = ProcessIDXB(index, key);
            break;
        case SHEN_NAME(IDXC):
            record = ProcessIDXC(index, key);
            break;
        case SHEN_NAME(IDXD):
            record = ProcessSubtitleFile(index, code);
            break;
        default:
            return nullptr;
        }
        if (record)
            break;
    }
    if (!record) {
        if (sceneRemap && GetConversationAudioLanguage() == 1 && !std::strcmp(FindSceneTextRemapped(code.data(), 1), " "))
            *sceneRemap = 1;
        return nullptr;
    }
    if (restoreCode == 1)
        std::strncpy(code.data(), voiceCode, code.size());
    ConversationBuffer *buffer = nullptr;
    for (ConversationBuffer &candidate : conversationData.buffers)
        if (!candidate.callback) {
            buffer = &candidate;
            break;
        }
    if (currentDialogue && static_cast<std::uint16_t>(record[3] >> 16) != 0xffff)
        RetireSubtitles();
    const std::int32_t priority = static_cast<std::int32_t>(playFlags & 15U);
    const std::int32_t output = (playFlags & 0x10U) ? 2 : 1;
    const std::uint32_t outputFlags = static_cast<std::uint32_t>(output) | ((playFlags >> 2U) & 0x10U);
    if (buffer) {
        buffer->playFlags = playFlags;
        ConfigureConversationVoiceCategory(buffer->stream, voiceCode);
        buffer->sourceCode = voiceCode;
        buffer->bankName = reinterpret_cast<const char *>(resource->archive->reserved10);
        if (!StartStream(buffer->stream, resource->archive->index, static_cast<std::uint16_t>(record[3]), outputFlags, playFlags))
            buffer = nullptr;
    }
    if (!buffer) {
        for (ConversationBuffer &candidate : conversationData.buffers) {
            if (candidate.callback && priority <= candidate.priority && candidate.output == output) {
                ReleaseBuffer(candidate);
                ConfigureConversationVoiceCategory(candidate.stream, voiceCode);
                StartStream(candidate.stream, resource->archive->index, static_cast<std::uint16_t>(record[3]), outputFlags, playFlags);
                buffer = &candidate;
                break;
            }
        }
        if (!buffer)
            return nullptr;
    }
    if (static_cast<std::uint16_t>(record[3] >> 16) == 0xffff) {
        buffer->packetOffset = -1;
        buffer->callback = UpdateStream;
        buffer->packetRequest = nullptr;
    } else {
        const std::uint32_t pendingTag = SHEN_NAME(SEGA);
        std::memcpy(buffer->packet->data.data(), &pendingTag, sizeof(pendingTag));
        buffer->packetRequest = RequestConversationPacket(
            resource->archive, static_cast<std::uint16_t>(record[3] >> 16), std::bit_cast<std::int32_t>(record[4]) / 2048, buffer->packet->data.data());
        std::strcpy(buffer->packet->bankName.data(), resource->bankName.data());
        currentDialogue = buffer;
        buffer->packet->entry = static_cast<std::uint16_t>(record[3] >> 16);
        buffer->packet->sector = std::bit_cast<std::int32_t>(record[4]) / 2048;
        buffer->packet->pending = 1;
        buffer->packetOffset = static_cast<std::int32_t>(record[4] & 0x7ffU);
        buffer->callback = UpdatePacket;
        SetCameraCode(*buffer, code);
    }
    buffer->speaker = speaker.name == SHEN_NAME(null) ? shen_name{} : speaker;
    std::strncpy(buffer->code.data(), code.data(), buffer->code.size());
    if (showSubtitles && buffer->speaker.name) {
        const char *text = FindSceneTextRemapped(buffer->code.data(), GetConversationAudioLanguage() == 1);
        HLib::Task *scenario = ScenarioTask();
        const bool isRyo = ScenarioCharacterIsRyo(buffer->speaker);
        subtitleDestroyFrames = 0;
        shenPrepareDialogue(scenario, 1, text, isRyo);
    } else {
        showSubtitles = false;
    }
    buffer->output = output;
    buffer->subtitles = showSubtitles;
    buffer->resource = resource;
    buffer->priority = priority;
    const std::uint32_t initialVolume = 65536;
    std::memcpy(&buffer->volume, &initialVolume, sizeof(initialVolume));
    buffer->duckVolume = 1;
    if (!shenIsInIntro() && priority >= 4) {
        buffer->volume = -999;
        ApplyVolume(*buffer, -999);
    }
    return buffer;
}

