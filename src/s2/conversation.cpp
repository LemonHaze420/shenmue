void LoadIndex(const char *bankName) {
    ConversationResource *resource = resources;
    for (std::uint32_t remaining = 16; remaining != 0; --remaining, ++resource) {
        if (!resource->bankName[0])
            break;
        if (!std::strcmp(resource->bankName.data(), bankName))
            return;
    }
    std::strcpy(resource->bankName.data(), bankName);
    ConversationResource *cached = FindCachedResource(bankName);
    std::size_t size;
    if (cached && cached->index) {
        resource->index = cached->index;
        size = cachedIndexSizes[static_cast<std::size_t>(cached - cachedResources.data())];
    } else
        resource->index = AllocateIndex(bankName, g_actNumber, 0, size);
    indexSizes[static_cast<std::size_t>(resource - resources)] = size;
}

AfsArchiveSlot *ReadConversationArchive(const char *bankName, std::int32_t actNumber, std::int32_t capacity, void *memory) {
    char directory[40], filename[16];
    std::sprintf(directory, "SCENE/%02d/STREAM/PC/%s/%s", actNumber, GetConversationAudioLanguage() ? "JAP" : "ENG", bankName);
    char *separator = std::strrchr(directory, '/');
    *separator = '\0';
    std::strcpy(filename, separator + 1);
    std::strcat(filename, ".AFS");
    AfsArchiveSlot *archive = LoadAfsArchive(directory, filename, capacity, memory);
    archive->reserved10 = reinterpret_cast<std::uintptr_t>(bankName);
    std::strncpy(currentAfsName, bankName, 4);
    return archive;
}

bool LoadArchive(const char *bankName) {
    ConversationResource *resource = resources;
    for (std::uint32_t remaining = 16; remaining != 0; --remaining, ++resource)
        if (!std::strcmp(resource->bankName.data(), bankName))
            break;
    if (!resource->archive) {
        ConversationResource *cached = FindCachedResource(bankName);
        resource->archive = cached ? cached->archive : nullptr;
        if (!resource->archive) {
            std::uint16_t capacity;
            std::memcpy(&capacity, resource->index + 8, sizeof(capacity));
            resource->archive = ReadConversationArchive(bankName, g_actNumber, capacity, nullptr);
        }
        if (!resource->archive) {
            resource->bankName[0] = '\0';
            HLib::FreeTaskData(resource->index);
        }
    }
    return true;
}

