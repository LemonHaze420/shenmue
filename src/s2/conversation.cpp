void scenDestroySubtitles(HLib::Task *task) {
    EndSubtitlePresentation();
    auto *scenario = ScenarioData(task);
    if (!scenario)
        return;
    scenario->windowTextState.scenarioStateFlags = 18;
    if (scenario->windowDialog) {
        std::uint32_t flags{};
        std::memcpy(&flags, scenario->windowDialog, sizeof(flags));
        flags &= ~0x20U;
        std::memcpy(scenario->windowDialog, &flags, sizeof(flags));
    }
    scenario->field0e4 = 0;
}

void ForceScenarioSubtitles(HLib::Task *task) {
    auto *scenario = ScenarioData(task);
    if (!scenario || (scenario->windowTextState.scenarioStateFlags & 0x12U))
        return;

    if (scenario->windowTextState.scenarioStateFlags & 4U) {
        if (scenario->windowDialog) {
            std::uint32_t flags{};
            std::memcpy(&flags, scenario->windowDialog, sizeof(flags));
            flags |= 0x30U;
            std::memcpy(scenario->windowDialog, &flags, sizeof(flags));
        }
        scenario->windowTextState.scenarioStateFlags ^= 4U;
    } else
        scenario->windowTextState.scenarioStateFlags |= 8U;
}

