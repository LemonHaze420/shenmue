const std::uint32_t *FindConversationIndexChunk(const std::uint32_t *chunk, std::uint32_t wanted) {
    while (chunk[0] != wanted) {
        const std::uint32_t size = chunk[1];
        if (!size)
            return nullptr;
        chunk = reinterpret_cast<const std::uint32_t *>(reinterpret_cast<const std::byte *>(chunk) + size);
    }
    return chunk;
}

// @verified - p
const std::uint32_t *ProcessIDXB(const std::uint32_t *index, const std::array<std::uint32_t, 3> &code) {
    const std::uint32_t *table = FindConversationIndexChunk(index, SHEN_NAME(TABL));
    if (!table)
        return nullptr;
    const std::uint32_t *groups = FindConversationIndexChunk(index, SHEN_NAME(SIDX));
    if (!groups)
        return nullptr;
    for (const std::uint32_t *group = groups + 2; group[0] != SHEN_NAME(eNDi); group += 2) {
        if (group[0] != code[0])
            continue;
        const std::int32_t begin = std::bit_cast<std::int32_t>(group[1]), end = std::bit_cast<std::int32_t>(group[3]);
        const std::uint32_t *entry = table + 2 + 4LL * begin;
        for (std::int32_t position = begin; position < end; ++position, entry += 4) {
            if (entry[0] != code[1] || entry[1] != code[2])
                continue;
            g_conversationIndexBRecord[0] = code[0];
            g_conversationIndexBRecord[1] = code[1];
            g_conversationIndexBRecord[2] = code[2];
            g_conversationIndexBRecord[3] = entry[2];
            g_conversationIndexBRecord[4] = entry[3];
            return g_conversationIndexBRecord.data();
        }
    }
    return nullptr;
}

