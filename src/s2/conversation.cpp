std::uint64_t GetConversationStreamPlaying(ConversationStream &stream) {
    if (!stream.handle)
        return 0;
    if (GetAuthorStreamingAudioEnabled())
        return PollDialogueVoice(stream.handle) == DialogueVoiceState::Playing;
    if (static_cast<std::uint32_t>(GetAuthorSilentStreamCounter()) == 4)
        return 0;
    stream.remainingFrames = std::bit_cast<std::int32_t>(static_cast<std::uint32_t>(stream.remainingFrames) - 1U);
    return stream.remainingFrames ? 3 : 0;
}

bool InitializeConversationStreamBuffers(ConversationStream &stream, std::uint32_t flags) {
    const bool playing = stream.handle && PollDialogueVoice(stream.handle) == DialogueVoiceState::Playing;
    if ((flags & 0x12U) || playing) {
        stream.compressedBuffer = g_conversationSecondaryVoiceBuffer;
        stream.decodeBuffer = g_conversationSecondaryCompressedBuffer;
    } else {
        stream.compressedBuffer = g_conversationVoiceBuffer;
        stream.decodeBuffer = g_conversationCompressedBuffer;
        stream.handle = AllocatePrimaryConversationStreamNullsub(reinterpret_cast<void *>(1U), stream.compressedBuffer, CONVERSATION_VOICE_BUFFER_SIZE);
    }
    return true;
}

bool StartStream(ConversationStream &stream, std::int32_t archive, std::uint16_t entry, std::uint32_t outputFlags, std::uint32_t playFlags) {
    if (!GetAuthorStreamingAudioEnabled()) {
        stream.handle = reinterpret_cast<DialogueVoice *>(&silentConversationStreamHandle);
        std::uint64_t &counter = GetAuthorSilentStreamCounter();
        const std::int32_t table = std::bit_cast<std::int32_t>(static_cast<std::uint32_t>(counter));
        if (table != 4) {
            const std::int32_t index = std::bit_cast<std::int32_t>(static_cast<std::uint32_t>(counter >> 32));
            stream.remainingFrames = CONVERSATION_SILENT_DURATIONS[table][index];
            counter = (static_cast<std::uint64_t>(static_cast<std::uint32_t>(index) + 1U) << 32) | static_cast<std::uint32_t>(counter);
        }
        return true;
    }
    StopConversationStream(stream);
    if (!InitializeConversationStreamBuffers(stream, outputFlags))
        return false;
    stream.volume = -1;
    stream.frameScale = 256;
    stream.cameraCode = 0;
    stream.paused = 0;
    stream.field2c = 30;
    const float gain = VoiceGain(stream.baseAttenuation, playFlags);
    InitializeConversationDecodeBufferNullsub(stream.handle, stream.decodeBuffer, CONVERSATION_COMPRESSED_BUFFER_SIZE);
    stream.handle = StartDialogueVoice(archive, entry, gain);
    SetDialogueVoiceVolume(stream.handle, gain);
    return true;
}

